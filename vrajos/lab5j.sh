echo "Enter a number between (1-7)"
read a

if [ $a -eq 1]
then
	echo "Monday"
fi

if [ $a -eq 2]
then
	echo "Tuesday"
fi

if [ $a -eq 3]
then
	echo "Wednesday"
fi

if [ $a -eq 4]
then
	echo "Thursday"
fi

if [ $a -eq 5]
then
	echo "Friday"
fi

if [ $a -eq 6]
then
	echo "Saturday"
fi

if [ $a -eq 7]
then
	echo "Sunday"
fi
